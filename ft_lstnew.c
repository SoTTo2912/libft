#include "libft.h"

t_list	*ft_lstnew(void *content)
{
	t_list	*new;

	new = NULL;
	new = (t_list *)malloc(sizeof(t_list));
	if (!new)
	{
		return (0);
	}
	new->content = content;
	new->next = NULL;
	return (new);
}
